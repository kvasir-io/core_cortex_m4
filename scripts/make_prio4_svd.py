#!/usr/bin/env python3
"""core_prio4.svd out of core.svd: the same Cortex-M4 with 4 priority bits instead of 3.

The number of implemented priority bits is the chip vendor's choice. core.svd has 3 (SAM D5x/E5x:
nvicPrioBits 3, priority in bits [7:5] of each byte); the STM32F4 family has 4 (PM0214 4.3.7:
"implements only bits[7:4] of each field, bits[3:0] read as zero and ignore writes"; RM0430 10.1:
"16 programmable priority levels (4 bits of interrupt priority are used)").
core_cortex_common's Nvic derives the priority range from the PRI fields, so those fields - and
only those - differ between the two files:

- <nvicPrioBits> 3 -> 4
- NVIC_IPRn PRI_%s: bitOffset 5 -> 4, bitWidth 3 -> 4
- SCB SHPR1..3 PRI_4..PRI_15: [31:29] [23:21] [15:13] [7:5] -> [31:28] [23:20] [15:12] [7:4]

A chip selects it with set(CORE_NVIC_PRIO_BITS 4) before including cmake/core.cmake.

    scripts/make_prio4_svd.py          write core_prio4.svd
    scripts/make_prio4_svd.py --check  exit 1 if core_prio4.svd is not what core.svd gives
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = "PM0214 4.3.7 / 4.4.8, RM0430 10.1"


def comment(what: str) -> str:
    return f"<!-- Kvasir: {what}, 4 implemented priority bits [7:4] ({SOURCE}); made by scripts/make_prio4_svd.py -->"


def convert(svd: str) -> str:
    svd, n = re.subn(r"<nvicPrioBits>3</nvicPrioBits>",
                     "<nvicPrioBits>4</nvicPrioBits>", svd)
    assert n == 1, "nvicPrioBits"

    # NVIC_IPRn: the dim'd PRI_%s field.
    ipr = re.compile(
        r"(?P<indent>[ \t]*)<name>PRI_%s</name>\n"
        r"(?P<desc>[ \t]*<description>)[^<]*(</description>\n)"
        r"(?P<off>[ \t]*)<bitOffset>5</bitOffset>\n"
        r"(?P<wid>[ \t]*)<bitWidth>3</bitWidth>\n")

    def ipr_field(m: re.Match) -> str:
        return (f"{m['indent']}{comment('NVIC_IPRn priority field')}\n"
                f"{m['indent']}<name>PRI_%s</name>\n"
                f"{m['desc']}Priority of interrupt 4n+m. This core is configured with nvicPrioBits = 4"
                f" (STM32F4: sixteen priority levels), so only the top four bits of each byte, [7:4],"
                f" are implemented; the rest read as zero and ignore writes</description>\n"
                f"{m['off']}<bitOffset>4</bitOffset>\n"
                f"{m['wid']}<bitWidth>4</bitWidth>\n")

    svd, n = ipr.subn(ipr_field, svd)
    assert n == 1, "NVIC_IPRn PRI_%s"

    # SHPR1..3: PRI_4 .. PRI_15, one byte each.
    shpr = re.compile(r"(?P<indent>[ \t]*)<name>PRI_(?P<n>[0-9]+)</name>(?P<mid>(?:(?!</field>).)*?)"
                      r"<bitRange>\[(?P<hi>[0-9]+):(?P<lo>[0-9]+)\]</bitRange>", re.S)

    def shpr_field(m: re.Match) -> str:
        hi, lo = int(m["hi"]), int(m["lo"])
        assert hi - lo == 2 and lo % 8 == 5, f"PRI_{m['n']} [{hi}:{lo}]"
        return (f"{m['indent']}{comment(f'SHPR PRI_{m['n']}')}\n"
                f"{m['indent']}<name>PRI_{m['n']}</name>{m['mid']}<bitRange>[{hi}:{lo - 1}]</bitRange>")

    svd, n = shpr.subn(shpr_field, svd)
    assert n == 12, f"SHPR fields: {n}"

    svd, n = re.subn(r"(<\?xml[^>]*\?>\n)",
                     r"\1<!-- Kvasir: core.svd with 4 priority bits (STM32F4) - generated by "
                     r"scripts/make_prio4_svd.py, do not edit; edit core.svd and run it -->\n",
                     svd, count=1)
    assert n == 1
    return svd


def main() -> None:
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        raise SystemExit(__doc__)
    made = convert((ROOT / "core.svd").read_text(encoding="utf-8"))
    out = ROOT / "core_prio4.svd"
    if check:
        if not out.exists() or out.read_text(encoding="utf-8") != made:
            raise SystemExit(f"{out} is stale: run scripts/make_prio4_svd.py")
        print(f"{out}: up to date")
        return
    out.write_text(made, encoding="utf-8")
    print(f"{out}: written")


if __name__ == "__main__":
    main()
